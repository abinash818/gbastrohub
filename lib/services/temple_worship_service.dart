    if (bhavaFromLagna == 1) {
      return 'இன்மையில் நன்மை தருவார் கோவில், மதுரை';
    }

    final String rasi = rasiTamil.trim();
    final bool isMeshamVrischigam = rasi == 'மேஷம்' || rasi == 'விருச்சிகம்';
    final bool isRishabamThulam = rasi == 'ரிஷபம்' || rasi == 'துலாம்';
    final bool isMithunamKanni = rasi == 'மிதுனம்' || rasi == 'கன்னி';
    final bool isKadagam = rasi == 'கடகம்';
    final bool isSimmam = rasi == 'சிம்மம்';
    final bool isDhanusuMeenam = rasi == 'தனுசு' || rasi == 'மீனம்';
    final bool isMakaramKumbam = rasi == 'மகரம்' || rasi == 'கும்பம்';

