    if (cleanKarana == 'விஷ்டி') cleanKarana = 'பத்திரை';
    if (cleanKarana == 'தைதுலை') cleanKarana = 'தைதுளை';
    if (cleanKarana == 'சதுஷ்பாதம்') cleanKarana = 'சதுஸ்பாதம்';
    if (cleanKarana == 'கிம்துக்கினம்') cleanKarana = 'கிமிஸ்துக்கினம்';
    if (cleanKarana.isEmpty) cleanKarana = 'பவம்';

    final karanaInfo = KARANA_TEMPLES[cleanKarana] ?? KARANA_TEMPLES['பவம்']!;

    // 5. Vainasika (வைநாசிக நட்சத்திரக் கோவில்)
    final vainasikaData = results['vainasika_pada'] as Map? ?? {};
    String rawVainasika = vainasikaData['vainasika_nakshatra']?.toString() ?? '';
    String vainasikaNak = '';
    for (var s in tamilStarNames) {
      if (rawVainasika.contains(s)) {
        vainasikaNak = s;
        break;
      }
    }
    if (vainasikaNak.isEmpty) {
      for (var entry in ENGLISH_TO_TAMIL_STARS.entries) {
        if (rawVainasika.toLowerCase().contains(entry.key.toLowerCase())) {
          vainasikaNak = entry.value;
          break;
        }
      }
    }
    if (vainasikaNak.isEmpty) vainasikaNak = rawVainasika;
    final String vainasikaTemple = VAINASIKA_TEMPLES[vainasikaNak] ?? 'சேரன்மாதேவி சந்திரமௌலீஸ்வரர்';
    final int vainasikaPada = vainasikaData['vainasika_pada'] as int? ?? 1;

    // 6. Mudakku (முடக்கு ராசி / பாவகக் கோவில்)
    final mudakkuData = yogiAvayogi['mudakku'] as Map? ?? {};
    String mudakkuRasi = mudakkuData['rasi_tamil']?.toString() ??
                         (mudakkuData['rasi'] != null ? KPService.TAMIL_SIGNS[mudakkuData['rasi']] : null) ??
                         mudakkuData['rasi']?.toString() ??
                         '';
    final int mudakkuRasiIdx = mudakkuData['rasi_idx'] as int? ?? 0;

    // Lagna rasi index
    int lagnaRasiIdx = 0;
    if (planetDetails['lagna'] != null && planetDetails['lagna']['longitude'] != null) {
      double lLon = (planetDetails['lagna']['longitude'] as num).toDouble();
      lagnaRasiIdx = (lLon / 30).floor() % 12;
    }
    int bhavaFromLagna = ((mudakkuRasiIdx - lagnaRasiIdx + 12) % 12) + 1;
    final String mudakkuTemple = getMudakkuTemple(bhavaFromLagna, mudakkuRasi);

    return {
      'birth_star': cleanStar,
      'birth_star_temple': birthStarTemple,
      'yoga_name': cleanYoga,
      'yogi_planet': yogiPlanet,
      'yogi_temple': yogiTemple,
      'avayogi_planet': avayogiPlanet,
      'avayogi_temple': avayogiTemple,
      'thithi_name': cleanThithi,
      'is_shukla': isShukla,
      'thithi_deity': thithiInfo['deity'] ?? '',
      'thithi_temple': thithiInfo['temple'] ?? '',
      'karana_name': cleanKarana,
      'karana_lord': karanaInfo['lord'] ?? '',
      'karana_animal': karanaInfo['animal'] ?? '',
      'karana_deity': karanaInfo['deity'] ?? '',
      'karana_temple': karanaInfo['temple'] ?? '',
      'vainasika_nak': vainasikaNak,
      'vainasika_pada': vainasikaPada,
      'vainasika_temple': vainasikaTemple,
      'mudakku_rasi': mudakkuRasi,
      'mudakku_bhava': bhavaFromLagna,
      'mudakku_temple': mudakkuTemple,
    };
  }
