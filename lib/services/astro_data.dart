  static String getRaasi(String natchathira, int paatham) {
    int natchIdx = natchathiraList.indexOf(natchathira);
    if (natchIdx == -1) return "";
    int totalPaathams = (natchIdx * 4) + paatham;
    int raasiIdx = (totalPaathams - 1) ~/ 9;
    if (raasiIdx >= 0 && raasiIdx < raasiList.length) {
      return raasiList[raasiIdx];
    }
    return "";
  }
