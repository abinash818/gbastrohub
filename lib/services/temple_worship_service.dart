        if (isKadagam) return 'ஓசூர் சந்திரசூடேஸ்வரர்';
        if (isSimmam) return 'கொடுமுடி மகுடேஸ்வரர்';
        if (isDhanusuMeenam) return 'திருத்துறையூர் சிஷ்டகுருநாதர் (பண்ருட்டி அருகில்)';
